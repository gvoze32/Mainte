# `mainte layout`: align the text column and its sections with the artwork.
# shellcheck shell=sh

layout_usage() {
    printf '%s\n' \
        'Usage: mainte layout [show|reset|set ITEM PX]' \
        '' \
        'Without arguments, opens an interactive editor. Changes are saved to' \
        'mainte.layout and applied immediately when Mainte is running.' \
        '' \
        "Items: $MAINTE_LAYOUT_ITEMS" \
        'Offsets are pixels relative to the original layout:' \
        '  text-x moves the whole text column (positive = right);' \
        '  text-y and the sections move down when positive.'
}

layout_label() {
    case $1 in
        text-x) printf 'Text column X' ;;
        text-y) printf 'Text column Y' ;;
        *) printf '%s' "$1" | awk '{ print toupper(substr($0, 1, 1)) substr($0, 2) }' ;;
    esac
}

layout_item() { # layout_item NAME-OR-NUMBER
    _index=0
    for _item in $MAINTE_LAYOUT_ITEMS; do
        _index=$((_index + 1))
        if [ "$1" = "$_item" ] || [ "$1" = "$_index" ]; then
            printf '%s\n' "$_item"
            return 0
        fi
    done
    return 1
}

layout_save() {
    mkdir -p "$(dirname -- "$MAINTE_LAYOUT_FILE")"
    _temporary=$MAINTE_LAYOUT_FILE.tmp.$$
    {
        printf '%s\n' '# Generated by mainte layout; offsets in pixels.'
        for _item in $MAINTE_LAYOUT_ITEMS; do
            printf '%s=%s\n' "$(layout_var "$_item")" "$(layout_get "$_item")"
        done
    } > "$_temporary"
    mv "$_temporary" "$MAINTE_LAYOUT_FILE"
}

# Save, then re-render the running overlay so every change is visible at once.
layout_apply() {
    layout_save
    if mainte_is_running; then
        sh "$MAINTE_ROOT/mainte" reload >/dev/null
        printf 'Saved and applied.\n'
    else
        printf 'Saved to %s (start Mainte with: mainte run).\n' "$MAINTE_LAYOUT_FILE"
    fi
}

layout_show() {
    _index=0
    for _item in $MAINTE_LAYOUT_ITEMS; do
        _index=$((_index + 1))
        printf '%4s) %-14s %5s px\n' "$_index" "$(layout_label "$_item")" "$(layout_get "$_item")"
    done
}

layout_reset() {
    for _item in $MAINTE_LAYOUT_ITEMS; do
        layout_set "$_item" 0
    done
}

layout_interactive() {
    [ -t 0 ] || die 'interactive layout needs a terminal; use: mainte layout set ITEM PX'
    _count=0
    for _item in $MAINTE_LAYOUT_ITEMS; do
        _count=$((_count + 1))
    done
    while :; do
        printf '\nMainte layout (pixels; positive = down, or right for Text column X)\n'
        layout_show
        printf 'Choose 1-%s, r = reset all, q = quit: ' "$_count"
        IFS= read -r _choice || {
            printf '\n'
            return 0
        }
        case $_choice in
            q|Q) return 0 ;;
            r|R)
                layout_reset
                layout_apply
                continue
                ;;
        esac
        if ! _item=$(layout_item "$_choice"); then
            printf 'Unknown choice: %s\n' "$_choice" >&2
            continue
        fi

        _current=$(layout_get "$_item")
        printf '%s is %s px. Nudge with +N/-N, set with =N, blank to go back: ' \
            "$(layout_label "$_item")" "$_current"
        IFS= read -r _input || return 0
        case $_input in
            '') continue ;;
            =*) _value=${_input#=} ;;
            [+-]*)
                is_int "$_input" || {
                    printf 'Not a number: %s\n' "$_input" >&2
                    continue
                }
                _value=$((_current + $(to_int "$_input")))
                ;;
            *)
                printf 'Use +N, -N, or =N.\n' >&2
                continue
                ;;
        esac
        if ! is_int "$_value"; then
            printf 'Not a number: %s\n' "$_value" >&2
            continue
        fi
        layout_set "$_item" "$(to_int "$_value")"
        layout_apply
    done
}

cmd_layout() {
    case ${1:-} in
        '')
            layout_interactive
            ;;
        show)
            layout_show
            ;;
        reset)
            layout_reset
            layout_apply
            ;;
        set)
            [ "$#" -eq 3 ] || die 'usage: mainte layout set ITEM PX'
            _item=$(layout_item "$2") || die "unknown layout item: $2 (items: $MAINTE_LAYOUT_ITEMS)"
            is_int "$3" || die "offset must be an integer: $3"
            layout_set "$_item" "$(to_int "$3")"
            layout_apply
            ;;
        -h|--help|help)
            layout_usage
            ;;
        *)
            layout_usage >&2
            exit 2
            ;;
    esac
}
